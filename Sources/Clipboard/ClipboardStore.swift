import AppKit

struct ClipItem: Codable, Equatable, Identifiable {
    let id: UUID
    var text: String
    var date: Date
    var sourceApp: String?
    var pinned: Bool = false
    /// For screenshots: the PNG's file name in the Images folder. `text` is then just a label.
    var image: String?
    /// Pixels per point of the screenshot, so it pastes at its on-screen size.
    var imageScale: Double?

    var isImage: Bool { image != nil }

    init(id: UUID, text: String, date: Date, sourceApp: String?, pinned: Bool = false,
         image: String? = nil, imageScale: Double? = nil) {
        self.id = id
        self.text = text
        self.date = date
        self.sourceApp = sourceApp
        self.pinned = pinned
        self.image = image
        self.imageScale = imageScale
    }

    // Older history files have no "pinned", "image" or "imageScale" keys.
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(UUID.self, forKey: .id)
        text = try c.decode(String.self, forKey: .text)
        date = try c.decode(Date.self, forKey: .date)
        sourceApp = try c.decodeIfPresent(String.self, forKey: .sourceApp)
        pinned = try c.decodeIfPresent(Bool.self, forKey: .pinned) ?? false
        image = try c.decodeIfPresent(String.self, forKey: .image)
        imageScale = try c.decodeIfPresent(Double.self, forKey: .imageScale)
    }
}

/// Watches the general pasteboard and keeps a de-duplicated, persisted history of copied text.
/// Screenshots taken with Capture are added explicitly (other copied images are not recorded).
///
/// `items` is always ordered: pinned items first (in the order they were pinned), then the
/// rest newest-first. Pinned items keep their place when re-copied, don't count toward
/// `maxItems`, and survive Clear History.
@MainActor
final class ClipboardStore {
    private(set) var items: [ClipItem] = []
    var maxItems: Int
    var isPaused = false
    var onChange: (() -> Void)?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let fileURL: URL
    let imagesDir: URL

    /// Pasteboard types that password managers and other apps use to say "don't record this".
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(maxItems: Int) {
        self.maxItems = maxItems
        self.lastChangeCount = pasteboard.changeCount
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipboardManager", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        self.fileURL = dir.appendingPathComponent("history.json")
        self.imagesDir = dir.appendingPathComponent("Images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        load()
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.1
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        add(text, source: NSWorkspace.shared.frontmostApplication?.localizedName)
    }

    var pinnedCount: Int { items.prefix { $0.pinned }.count }

    private func add(_ text: String, source: String?) {
        if let idx = items.firstIndex(where: { !$0.isImage && $0.text == text }) {
            bumpToTop(at: idx)
        } else {
            items.insert(ClipItem(id: UUID(), text: text, date: Date(), sourceApp: source), at: pinnedCount)
        }
        trim()
        changed()
    }

    /// Adds text typed in by hand to the top of the history (or moves an identical item there).
    /// Returns the item's id, or nil if the text is blank.
    @discardableResult
    func addText(_ text: String) -> UUID? {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        add(text, source: nil)
        return items.first { !$0.isImage && $0.text == text }?.id
    }

    /// Replaces a text item's contents, keeping its place in the list. Blank text is ignored.
    /// Any other item with the same text is dropped, so the history stays de-duplicated.
    func update(id: UUID, text: String) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              let idx = items.firstIndex(where: { $0.id == id }),
              !items[idx].isImage, items[idx].text != text else { return }
        items[idx].text = text
        items.removeAll { $0.id != id && !$0.isImage && $0.text == text }
        changed()
    }

    /// Marks an item as just used: unpinned items move to the top of the unpinned list,
    /// pinned items stay where they are.
    private func bumpToTop(at idx: Int) {
        items[idx].date = Date()
        guard !items[idx].pinned else { return }
        let moved = items.remove(at: idx)
        items.insert(moved, at: pinnedCount)
    }

    /// Adds a screenshot to the top of the history. The PNG is kept in the Images folder.
    func addImage(_ image: CGImage, pointScale: CGFloat, source: String?) {
        let rep = NSBitmapImageRep(cgImage: image)
        guard let png = rep.representation(using: .png, properties: [:]) else { return }
        let id = UUID()
        let name = id.uuidString + ".png"
        let url = imagesDir.appendingPathComponent(name)
        do {
            try png.write(to: url, options: [.atomic])
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        } catch {
            NSLog("GregsUtils: couldn't save screenshot to history: \(error)")
            return
        }
        let label = "Screenshot \(image.width) × \(image.height)"
        items.insert(ClipItem(id: id, text: label, date: Date(), sourceApp: source,
                              image: name, imageScale: Double(pointScale)), at: pinnedCount)
        trim()
        changed()
    }

    func imageURL(for item: ClipItem) -> URL? {
        item.image.map { imagesDir.appendingPathComponent($0) }
    }

    /// Puts an item back on the clipboard and moves it to the top of the history.
    func copyToPasteboard(_ item: ClipItem) {
        if let url = imageURL(for: item) {
            guard let data = try? Data(contentsOf: url), let rep = NSBitmapImageRep(data: data) else { NSSound.beep(); return }
            pasteboard.clearContents()
            let scale = CGFloat(item.imageScale ?? 1)
            rep.size = NSSize(width: CGFloat(rep.pixelsWide) / scale, height: CGFloat(rep.pixelsHigh) / scale)
            if let png = rep.representation(using: .png, properties: [:]) { pasteboard.setData(png, forType: .png) }
            if let tiff = rep.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
        } else {
            pasteboard.clearContents()
            pasteboard.setString(item.text, forType: .string)
        }
        lastChangeCount = pasteboard.changeCount // don't re-record our own write
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            bumpToTop(at: idx)
            changed()
        }
    }

    /// Pinning appends to the end of the pinned block so existing pins keep their ⌘-number.
    /// Unpinning drops the item back into the history by date.
    func togglePin(id: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return }
        var item = items.remove(at: idx)
        item.pinned.toggle()
        if item.pinned {
            items.insert(item, at: pinnedCount)
        } else {
            let pins = pinnedCount
            let pos = items[pins...].firstIndex { $0.date < item.date } ?? items.count
            items.insert(item, at: pos)
        }
        changed()
    }

    /// Moves a pinned item up (-1) or down (+1) within the pinned block.
    func movePinned(id: UUID, by delta: Int) {
        guard let idx = items.firstIndex(where: { $0.id == id }), items[idx].pinned else { return }
        let target = idx + delta
        guard target >= 0, target < pinnedCount else { return }
        items.swapAt(idx, target)
        changed()
    }

    func remove(id: UUID) {
        deleteImages(of: items.filter { $0.id == id })
        items.removeAll { $0.id == id }
        changed()
    }

    /// Removes all unpinned items.
    func clear() {
        deleteImages(of: items.filter { !$0.pinned })
        items.removeAll { !$0.pinned }
        changed()
    }

    /// How many unpinned items a limit of `n` would delete right now.
    func overflow(ifLimitWere n: Int) -> Int { max(0, items.count - pinnedCount - n) }

    /// Changes the limit on unpinned items, deleting the oldest ones beyond it.
    func setMaxItems(_ n: Int) {
        maxItems = n
        trim()
        changed()
    }

    private func trim() {
        let limit = pinnedCount + maxItems
        if items.count > limit {
            deleteImages(of: Array(items[limit...]))
            items.removeLast(items.count - limit)
        }
    }

    private func deleteImages(of removed: [ClipItem]) {
        for item in removed {
            if let url = imageURL(for: item) { try? FileManager.default.removeItem(at: url) }
        }
    }

    private func changed() {
        save()
        onChange?()
    }

    // MARK: Persistence

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        // Restore the pinned-first ordering in case the file was edited by hand.
        items = decoded.filter(\.pinned) + decoded.filter { !$0.pinned }
        trim()
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: fileURL, options: [.atomic])
        // History can contain sensitive text; keep it readable by this user only.
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
    }
}
